program Arithmetic
    print *, 20+10     !addition
    print *, 20-10     !subtraction
    print *, 20*10     !multiplication
    print *, 20/10     !quotient
    print *, 2**10     !exponentiation or power
    print *, 1.0/3     !division
    print *, 1/3.0     !division
    print *, 1.0/3.0   !division
end program Arithmetic